const preferredLocale = (window.txConsts.preAuth && window.txConsts.preAuth.locale) || window.txConsts.uiLocale;
export const uiLocale: UiLocale = preferredLocale === 'hr' ? 'hr' : 'en';
export const isCroatian = uiLocale === 'hr';

export function t(key: string, values: Record<string, string | number> = {}) {
    const translated = uiLocale === 'hr' ? (hr[key] ?? key) : key;
    return translated.replace(/\{(\w+)\}/g, (match, name) => (
        Object.prototype.hasOwnProperty.call(values, name) ? String(values[name]) : match
    ));
}
